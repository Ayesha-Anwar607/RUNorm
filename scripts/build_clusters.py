"""
Runner: Build spelling-variant clusters from the top-1000 vocabulary.

Reads:   data/interim/vocab_frequency.csv
Writes:
  data/interim/clusters_for_review.csv    -- full cluster table for human review
  data/interim/cluster_summary.txt        -- human-readable cluster report

Usage:
  python scripts/build_clusters.py
"""

import sys
import logging
from pathlib import Path
from collections import defaultdict

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import pandas as pd
from runorm.normalizer.cluster import build_clusters, records_to_dataframe

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%H:%M:%S",
)
logger = logging.getLogger("RUNorm-Cluster")

VOCAB_CSV   = PROJECT_ROOT / "data" / "interim" / "vocab_frequency.csv"
OUT_REVIEW  = PROJECT_ROOT / "data" / "interim" / "clusters_for_review.csv"
OUT_SUMMARY = PROJECT_ROOT / "data" / "interim" / "cluster_summary.txt"
TOP_N       = 1000


def main():
    if not VOCAB_CSV.exists():
        logger.error(f"Vocab file not found: {VOCAB_CSV}. Run build_vocab_frequency.py first.")
        sys.exit(1)

    logger.info(f"Loading top-{TOP_N} vocabulary from {VOCAB_CSV.name}...")
    freq_df = pd.read_csv(VOCAB_CSV)

    # ---- Run clustering ----
    records = build_clusters(freq_df, top_n=TOP_N)

    # ---- Save review CSV ----
    review_df = records_to_dataframe(records)
    review_df.to_csv(OUT_REVIEW, index=False, encoding="utf-8")
    logger.info(f"Saved review table ({len(review_df)} rows) → {OUT_REVIEW.name}")

    # ---- Build & save human-readable summary report ----
    _write_summary(records, OUT_SUMMARY)
    logger.info(f"Saved cluster summary → {OUT_SUMMARY.name}")

    # ---- Terminal report ----
    _print_terminal_report(records)


def _write_summary(records, path: Path):
    """Write a formatted cluster summary for human inspection."""
    # Group by cluster_id
    clusters = defaultdict(list)
    for r in records:
        clusters[r.cluster_id].append(r)

    lines = []
    lines.append("=" * 65)
    lines.append("RUNORM — SPELLING VARIANT CLUSTER REPORT")
    lines.append(f"Top-{TOP_N} words | Generated by build_clusters.py")
    lines.append("=" * 65)
    lines.append("")

    high_clusters  = [c for c in clusters.values() if len(c) > 1 and c[0].confidence == "HIGH"]
    med_clusters   = [c for c in clusters.values() if len(c) > 1 and c[0].confidence == "MEDIUM"]
    single_clusters = [c for c in clusters.values() if len(c) == 1]

    lines.append(f"Total clusters        : {len(clusters)}")
    lines.append(f"Multi-word clusters   : {len(high_clusters) + len(med_clusters)}")
    lines.append(f"  HIGH confidence     : {len(high_clusters)}")
    lines.append(f"  MEDIUM confidence   : {len(med_clusters)}")
    lines.append(f"Single-word clusters  : {len(single_clusters)}")
    lines.append("")

    for label, cluster_list in [("HIGH", high_clusters), ("MEDIUM", med_clusters)]:
        lines.append("-" * 65)
        lines.append(f"{label} CONFIDENCE CLUSTERS")
        lines.append("-" * 65)
        for members in sorted(cluster_list, key=lambda m: -m[0].term_frequency):
            proposed = members[0].proposed_canonical
            lines.append(f"\n  Canonical: '{proposed}'   (phonetic key: {members[0].phonetic_key})")
            for r in members:
                marker = " ← PROPOSED CANONICAL" if r.variant == proposed else ""
                lines.append(f"    {r.variant:<20} freq={r.term_frequency:>6,}  "
                              f"df={r.document_frequency:>5,}  key={r.phonetic_key}{marker}")
        lines.append("")

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def _print_terminal_report(records):
    clusters = defaultdict(list)
    for r in records:
        clusters[r.cluster_id].append(r)

    multi = [(cid, m) for cid, m in clusters.items() if len(m) > 1]
    logger.info("")
    logger.info("=" * 65)
    logger.info("CLUSTER REPORT — MULTI-WORD CLUSTERS (first 25)")
    logger.info("=" * 65)

    shown = 0
    for cid, members in sorted(multi, key=lambda x: -x[1][0].term_frequency):
        if shown >= 25:
            break
        variants_str = " | ".join(
            f"{r.variant}({r.term_frequency:,})" for r in members
        )
        canonical = members[0].proposed_canonical
        conf = members[0].confidence
        logger.info(f"[{conf}] → '{canonical}'  :  {variants_str}")
        shown += 1

    logger.info("=" * 65)
    logger.info(f"See full report: {OUT_REVIEW.name}")


if __name__ == "__main__":
    main()
